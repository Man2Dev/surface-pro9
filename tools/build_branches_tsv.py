#!/usr/bin/env python3
"""Build data/indexes/branches.tsv from the two branch scans.
usage: build_branches_tsv.py LS_BRANCHES.json KERNEL_BRANCHES.json OUT.tsv
Inputs: output of fork_branches.py (part A) and kernel_fork_branches.py (part B)."""
import json,sys
rows=json.load(open(sys.argv[1])); kf=json.load(open(sys.argv[2]))
H=['# Branches that carry work not in upstream, snapshot 2026-11-12/13.',
'# Part A: forks of linux-surface/linux-surface (patch-series repos). ahead = commits not reachable from any origin branch.',
'#   sp9 = an ahead commit mentions the Surface Pro 9. latest_patches = newest patches/<ver> dir on the branch.',
'# Part B: feature branches of linux-surface/kernel forks (kernel trees). novel = top commits (before the first stable',
'#   backport) whose subject is not in any linux-surface patches/ dir. Old djrscally 2020 to 2023 branches omitted.',
'# Generated by tools/fork_branches.py, tools/kernel_fork_branches.py and tools/build_branches_tsv.py. Raw: data/generated/*branches*.json',
'part\trepo\tbranch\tlast_date\tahead_or_novel\tsp9\tlatest_patches\ttip_or_novel_subjects']
out=H+['\t'.join(['A',*r[:6],r[6].replace('\t',' ')]) for r in rows]
for o in kf:
    if o['repo'].startswith('djrscally'): continue
    nk=[c for c in o['commits'] if not c['known']]
    if not nk: continue
    out.append('\t'.join(['B',o['repo'],o['branch'],max(c['date'] for c in nk),str(len(nk)),'sp9' if any(c['sp9'] for c in nk) else '','',' | '.join(c['subject'] for c in nk[:6]).replace('\t',' ')]))
open(sys.argv[3],'w').write('\n'.join(out)+'\n')
print(len(out)-len(H),'rows')

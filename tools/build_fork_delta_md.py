#!/usr/bin/env python3
"""Render data/generated/fork-deltas.json (from tools/all_fork_deltas.py) into data/indexes/fork-deltas.md,
annotated with data/curated/sp9-relevance.yaml."""
import json, yaml, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'data/generated/fork-deltas.json')))
rel = yaml.safe_load(open(os.path.join(root, 'data/curated/sp9-relevance.yaml')))
def guess(e):
    r = rel.get(e['subject'])
    if r: return r.get('relevance', '?'), r.get('subsystem', '?')
    s = e['subject'].lower()
    if re.search(r'surface pro 9|\bsp9\b|pro 8/9|pro 8 and 9', s): return 'high*', '?'
    if re.search(r'ipu4|ipu3|surface pro 5|pro 7|go 2|laptop 7|laptop 1/2|pro 10|pro 11|imx681|ov8865|ov7251|dw9719|powercap|mwifiex|amd', s): return 'none*', '?'
    if re.search(r'ov5693|ov13858|ipu-bridge|int3472|vd55g', s): return 'medium*', 'camera'
    if re.search(r'ithc|ipts|thc', s): return 'medium*', 'touch-pen'
    if re.search(r'surface|aggregator|sam|gpe|button|typecover|type cover', s): return 'medium*', '?'
    return 'verify*', '?'
order = {'critical':0,'high':1,'high*':1,'medium':2,'medium*':2,'verify':3,'verify*':3,'low':4,'none':5,'none*':5}
rows = []
for e in d:
    forks = sorted({w.split('/')[0].replace('_linux-surface','').replace('_',' / ') for w in e['where']})
    r, sub = guess(e)
    rows.append((order.get(r,9), r, sub, e['file'].replace('.patch',''), e['subject'], e['author'].split('<')[0].strip().strip('"'), ', '.join(forks), ' '.join(e['links'])))
rows.sort()
with open(os.path.join(root, 'data/indexes/fork-deltas.md'), 'w') as f:
    f.write('# Patches carried by forks but not by linux-surface\n\n')
    f.write('Generated by `tools/build_fork_delta_md.py` from `data/generated/fork-deltas.json` (85 active forks of linux-surface/linux-surface, newest 6 branches each, latest patches/<ver>/ dir, commit subjects not present in any upstream patches/ dir).\n')
    f.write('Relevance with a `*` is a keyword guess, without it comes from `data/curated/sp9-relevance.yaml`.\n\n')
    f.write('| SP9 | subsystem | series file | subject | author | forks | links |\n|---|---|---|---|---|---|---|\n')
    for _, r, sub, fl, s, a, fk, ln in rows:
        f.write(f'| {r} | {sub} | {fl} | {s.replace("|","/")} | {a} | {fk} | {ln} |\n')
print(len(rows))

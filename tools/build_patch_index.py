#!/usr/bin/env python3
"""Merge parsed linux-surface patch metadata, the mainline apply check and the
curated SP9 relevance map into data/indexes/patches-<ver>.yaml and .md.

usage: build_patch_index.py <ver> <parsed.json> <upstream_check.json> [label]
"""
import json, sys, yaml, os
ver, parsed, check = sys.argv[1:4]
label = sys.argv[4] if len(sys.argv) > 4 else f'linux-surface patches/{ver}'
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rel = yaml.safe_load(open(os.path.join(root, 'data/curated/sp9-relevance.yaml')))
P = json.load(open(parsed)); C = {c['sha']: c for c in json.load(open(check))}
rows = []
for c in P:
    r = rel.get(c['subject'], {})
    u = C.get(c['sha'], {})
    rows.append(dict(
        series=c['series'], subject=c['subject'], author=c['author'], date=c['date'],
        source_sha=c['sha'], files=c['files'],
        links=c['tags'].get('Link', []) + c['tags'].get('Closes', []) + c['tags'].get('BugLink', []),
        fixes=c['tags'].get('Fixes', []),
        mentions_sp9=c['mentions_sp9'], mentions_sp8=c['mentions_sp8'],
        mainline_apply_check=u.get('mainline_status', '?'), mainline_check_detail=u.get('detail', ''),
        sp9_relevance=r.get('relevance', 'unclassified'), subsystem=r.get('subsystem', '?'),
        upstream_class=r.get('upstream_class', 'unknown'), note=r.get('note', '')))
out = os.path.join(root, 'data', 'indexes', f'patches-{label.replace("/","-").replace(" ","-")}')
yaml.safe_dump(dict(source=label, generated_by='tools/build_patch_index.py', commits=rows),
               open(out + '.yaml', 'w'), sort_keys=False, allow_unicode=True, width=120)
order = dict(critical=0, high=1, medium=2, verify=3, low=4, none=5, unclassified=6)
with open(out + '.md', 'w') as f:
    f.write(f'# {label}: commit index\n\nGenerated by `tools/build_patch_index.py`. Do not edit by hand, edit `data/curated/sp9-relevance.yaml` and regenerate.\n\n')
    f.write('Columns: SP9 relevance, upstream class (see `docs/conventions.md`), result of applying the commit to mainline (see `tools/upstream_check.py`).\n\n')
    f.write('| SP9 | subsystem | series | subject | author | mainline apply | class | note |\n|---|---|---|---|---|---|---|---|\n')
    for r in sorted(rows, key=lambda r: (order.get(r['sp9_relevance'], 9), r['series'])):
        a = r['author'].split('<')[0].strip().strip('"')
        f.write(f"| {r['sp9_relevance']} | {r['subsystem']} | {r['series'].replace('.patch','')} | {r['subject']} | {a} | {r['mainline_apply_check']} {r['mainline_check_detail']} | {r['upstream_class']} | {r['note'].replace('|','/')} |\n")
print(out, len(rows), sum(1 for r in rows if r['sp9_relevance']=='unclassified'), 'unclassified')
